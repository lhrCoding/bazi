/**
 * 槽位注册表（TASKS T22；rules/report-sections.md §3 R-SLOT，ARCHITECTURE §4.3.1）。
 *
 * 代码与素材之间的契约：每个槽位一条，顺序 = 报告中的拼装顺序（同一章内按 md 表格行序；
 * 「CH2-ROLE-YONG / -XI / -JI」「CH6-CAREER / CH6-WEALTH / CH6-LOVE / CH6-HEALTH」一行展开为多个槽位）。
 * test/slots.test.ts 解析 md 中以 `| CH` 开头的表格行，与本表逐字段比对（id、名称、必需、维度原文、选几条、字数、
 * 依据模板、润色、无时辰）；初稿由脚本从 md 生成，此后两边任一改动未同步即测试失败。
 *
 * 结构化字段（md 只有自然语言，这里补全，供 lint L2 与覆盖率使用）：
 * - source：material（从素材库选）/ code（代码模板，不走素材）/ fixed（固定文本，1 变体）。
 * - loop：循环槽位（按 item 逐个选段，素材条件引用 item.* 字段）。
 * - dimensionFields / modifierFields：必需槽位的素材 when 只能引用这两组字段（texts/README.md §4.4）；
 *   null = 不限制（非必需槽位、代码模板、固定文本），或字段字典尚缺（见 gap）。
 * - length：「每条字数」可解析为区间时给出 [下限, 上限]，否则 null（原文见 lengthText）。
 */

export type SlotSource = 'material' | 'code' | 'fixed';

export interface SlotDef {
  id: string;
  chapter: number;
  name: string;
  required: boolean;
  source: SlotSource;
  loop: boolean;
  /** 非循环但由拼装代码传入单个 item（CH5-TRANSITION 的下一步大运、CH7-CAREER-NOW 的当前大运），素材可引用 item.* 字段 */
  itemContext?: true;
  /** md「维度」列原文 */
  dimension: string;
  dimensionFields: readonly string[] | null;
  modifierFields: readonly string[];
  /** md「选几条」列原文 */
  pick: string;
  length: readonly [number, number] | null;
  lengthText: string | null;
  /** md「依据模板」列原文；第 6 章表格无此列为 null，「—」原样保留 */
  basis: string | null;
  polish: boolean;
  /** md「无时辰」列原文 */
  nohour: string;
  /** 规范缺口说明（字段字典尚无对应字段等） */
  gap?: string;
}

